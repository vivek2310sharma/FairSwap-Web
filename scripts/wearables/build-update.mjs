// Generate a NEW forward-only update; never rewrites the foundation seed.
// Usage: node scripts/wearables/build-update.mjs --migration=<new CLI-created .sql> [--check]
import {readFileSync, writeFileSync} from 'node:fs';
import {createHash} from 'node:crypto';
import {resolve} from 'node:path';
import {buildCatalogue, seedSql, PATHS} from './build-catalogue.mjs';
const csv = readFileSync(PATHS.csv), corrections = JSON.parse(readFileSync(PATHS.corrections));
export function updateSql(supplement) {
  const before = buildCatalogue(csv, corrections), after = buildCatalogue(csv, corrections, supplement);
  if (before.revision !== '8dd5783ac9b7e12e') throw Error('V1 baseline drift');
  const tempSeed = seedSql(before).replaceAll('public.wearable_', 'pg_temp.expected_wearable_');
  const seed = seedSql(after)
    .replace('on conflict(singleton) do nothing', 'on conflict(singleton) do update set revision=excluded.revision,csv_sha256=excluded.csv_sha256,corrections_sha256=excluded.corrections_sha256,rows_total=excluded.rows_total,rows_approved=excluded.rows_approved')
    .replace('on conflict(id) do nothing', 'on conflict(id) do update set sort_order=excluded.sort_order')
    .replace('on conflict(id) do nothing', 'on conflict(id) do update set device_type=excluded.device_type,status=excluded.status,reason=excluded.reason,sort_order=excluded.sort_order');
  return `-- Generated by Web scripts/wearables/build-update.mjs. Review supplement.v1.1.json.
begin;
set local lock_timeout='5s';
set local statement_timeout='30s';
-- Serialize catalogue changes. No listing, session, context, flag, grant or function changes.
lock table public.wearable_catalogue_revision_v1, public.wearable_brands_v1, public.wearable_models_v1 in share row exclusive mode;
create temp table expected_wearable_catalogue_revision_v1 (like public.wearable_catalogue_revision_v1 including all) on commit drop;
create temp table expected_wearable_brands_v1 (like public.wearable_brands_v1 including all) on commit drop;
create temp table expected_wearable_models_v1 (like public.wearable_models_v1 including all) on commit drop;
${tempSeed}
do $$ begin
 if exists((select * from public.wearable_catalogue_revision_v1 except select * from pg_temp.expected_wearable_catalogue_revision_v1)
 union all (select * from pg_temp.expected_wearable_catalogue_revision_v1 except select * from public.wearable_catalogue_revision_v1))
 or exists((select * from public.wearable_brands_v1 except select * from pg_temp.expected_wearable_brands_v1)
 union all (select * from pg_temp.expected_wearable_brands_v1 except select * from public.wearable_brands_v1))
 or exists((select * from public.wearable_models_v1 except select * from pg_temp.expected_wearable_models_v1)
 union all (select * from pg_temp.expected_wearable_models_v1 except select * from public.wearable_models_v1)) then
 raise exception 'WEARABLES_V11_BASELINE_DRIFT'; end if;
end $$;
${seed}
do $$ begin
 if (select count(*) from public.wearable_models_v1) <> ${after.rows.length}
 or (select count(*) from public.wearable_models_v1 where status='approved') <> ${after.json.rows_approved}
 or (select revision from public.wearable_catalogue_revision_v1) is distinct from '${after.revision}' then
 raise exception 'WEARABLES_V11_SEED_INCONSISTENT'; end if;
end $$;
commit;
`;
}
export function updateManifest(supplement) {
  const before = buildCatalogue(csv, corrections), after = buildCatalogue(csv, corrections, supplement);
  const digest = c => createHash('md5').update([...c.rows].sort((a,b)=>a.id < b.id ? -1 : 1).map(r=>[r.id,r.brand_id,r.device_type,r.series,r.name,r.status,r.reason??'',r.source_row,r.sort_order].join('|')).join('\n')).digest('hex');
  return { oldRevision: before.revision, oldDigest: digest(before), revision: after.revision, digest: digest(after) };
}
const file = process.argv.find(x=>x.startsWith('--migration='))?.slice(12);
if (file) {
  const path = resolve(file);
  if (!path.includes('/wearables-v11/') || !/\d{14}_wearables_v11_catalogue\.sql$/.test(path)) throw Error('New wearables-v11 CLI-created candidate path required');
  const output = updateSql(JSON.parse(readFileSync(PATHS.supplement)));
  if (process.argv.includes('--check')) { if(readFileSync(path,'utf8')!==output) throw Error('Stale V1.1 migration'); }
  else { const prior=readFileSync(path,'utf8'); if(prior.trim() && !prior.startsWith('-- Generated by Web scripts/wearables/build-update.mjs.')) throw Error('Refusing to overwrite unrelated SQL'); writeFileSync(path,output); }
}
const manifest = process.argv.find(x=>x.startsWith('--manifest='))?.slice(11);
if (manifest) {
 const output = JSON.stringify(updateManifest(JSON.parse(readFileSync(PATHS.supplement))),null,2)+'\n';
 if(process.argv.includes('--check')) {if(readFileSync(manifest,'utf8')!==output)throw Error('Stale catalogue manifest');}
 else writeFileSync(manifest,output);
}
